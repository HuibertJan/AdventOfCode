    public override string Part1() => Run(false);

    private string Run(bool cornersStuck)
    {
        var grid = Input
            .Split(['\r', '\n'], StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries)
            .Select(line => line.Select(c => c == '#').ToArray())
            .ToArray();

        if (cornersStuck) SetCorners(grid);

        for (var step = 0; step < 100; step++)
        {
            grid = Step(grid);
            if (cornersStuck) SetCorners(grid);
        }

        return grid.Sum(row => row.Count(on => on)).ToString();
    }

    private static void SetCorners(bool[][] grid)
    {
        var last = grid.Length - 1;
        grid[0][0] = true;
        grid[0][^1] = true;
        grid[last][0] = true;
        grid[last][^1] = true;
    }

    private static bool[][] Step(bool[][] grid)
    {
        var rows = grid.Length;
        var next = new bool[rows][];
        for (var y = 0; y < rows; y++)
        {
            var cols = grid[y].Length;
            next[y] = new bool[cols];
            for (var x = 0; x < cols; x++)
            {
                var count = 0;
                for (var dy = -1; dy <= 1; dy++)
                {
                    for (var dx = -1; dx <= 1; dx++)
                    {
                        if (dx == 0 && dy == 0) continue;
                        var ny = y + dy;
                        var nx = x + dx;
                        if (ny >= 0 && ny < rows && nx >= 0 && nx < grid[ny].Length && grid[ny][nx])
                        {
                            count++;
                        }
                    }
                }

                next[y][x] = grid[y][x] ? count is 2 or 3 : count == 3;
            }
        }

        return next;
    }

